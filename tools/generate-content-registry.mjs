#!/usr/bin/env node

import {
  existsSync,
  lstatSync,
  readFileSync,
  readdirSync,
  writeFileSync,
} from "node:fs";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";
import {
  parseJsonFrontMatter,
  validateRepositoryStructuredContent,
} from "./lib/structured-content.mjs";

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const repositoryRoot = resolve(scriptDirectory, "..");
const lessonRoot = join(repositoryRoot, "book", "volumes");
const stagedLessonRoot = join(repositoryRoot, "drafts");
const assessmentRoot = join(repositoryRoot, "book", "assessments");
const referenceRoot = join(repositoryRoot, "book", "references");
const legacyMapPath = join(repositoryRoot, "book", "schema", "legacy-content-map.json");
const lessonPathsTarget = join(
  repositoryRoot,
  "learning-cockpit",
  "build",
  "generated-lesson-paths.ts",
);
const recordRegistryTarget = join(
  repositoryRoot,
  "learning-cockpit",
  "app",
  "lessons",
  "generated-structured-records.ts",
);
const learningIdsTarget = join(
  repositoryRoot,
  "learning-cockpit",
  "app",
  "my-learning",
  "generated-learning-lesson-ids.ts",
);
const checkOnly = process.argv.includes("--check");
const unexpectedArguments = process.argv.slice(2).filter((value) => value !== "--check");

if (unexpectedArguments.length > 0) {
  throw new Error(`unsupported arguments: ${unexpectedArguments.join(", ")}`);
}

function repositoryPath(absolutePath) {
  return relative(repositoryRoot, absolutePath).split(sep).join("/");
}

function collectFiles(root, predicate) {
  const files = [];
  const entries = readdirSync(root, { withFileTypes: true })
    .sort((left, right) => left.name.localeCompare(right.name));
  for (const entry of entries) {
    const entryPath = join(root, entry.name);
    if (entry.isDirectory()) files.push(...collectFiles(entryPath, predicate));
    else if (entry.isFile() && predicate(entry.name)) files.push(entryPath);
  }
  return files;
}

function readLessonDescriptor(file) {
  const parsed = parseJsonFrontMatter(readFileSync(file, "utf8"));
  if (parsed.issues.length > 0 || !parsed.metadata) {
    throw new Error(`cannot generate registry from invalid lesson: ${repositoryPath(file)}`);
  }
  return {
    id: parsed.metadata.id,
    order: parsed.metadata.order,
    volume: parsed.metadata.volume,
    path: repositoryPath(file),
  };
}

function readJsonDescriptor(file, expectedPrefix) {
  const value = JSON.parse(readFileSync(file, "utf8"));
  if (typeof value.id !== "string" || !value.id.startsWith(expectedPrefix)) {
    throw new Error(`invalid generated-registry ID in ${repositoryPath(file)}`);
  }
  return { id: value.id, path: repositoryPath(file) };
}

function variableName(prefix, id) {
  return `${prefix}${id.slice(id.indexOf("-") + 1)}`;
}

function relativeImport(fromFile, repositoryRelativePath) {
  const path = relative(dirname(fromFile), join(repositoryRoot, ...repositoryRelativePath.split("/")))
    .split(sep).join("/");
  return path.startsWith(".") ? path : `./${path}`;
}

function renderLessonPaths(lessons) {
  const rows = lessons.map(({ id, path }) => {
    const components = path.split("/").map((part) => JSON.stringify(part)).join(", ");
    return `  ${JSON.stringify(id)}: [${components}],`;
  });
  return [
    "// Generated by tools/generate-content-registry.mjs. Do not edit by hand.",
    "export const generatedLessonPaths = {",
    ...rows,
    "} as const;",
    "",
  ].join("\n");
}

function renderRecordRegistry(lessons, assessments, references) {
  const lessonImports = lessons.map(({ id }) =>
    `import ${variableName("lesson", id)}Raw from ${JSON.stringify(`virtual:book-lesson/${id}`)};`);
  const assessmentImports = assessments.map(({ id, path }) =>
    `import ${variableName("assessment", id)}Value from ${JSON.stringify(relativeImport(recordRegistryTarget, path))};`);
  const referenceImports = references.map(({ id, path }) =>
    `import ${variableName("reference", id)}Value from ${JSON.stringify(relativeImport(recordRegistryTarget, path))};`);
  const lessonValues = lessons.map(({ id }) => `  ${variableName("lesson", id)}Raw,`);
  const assessmentValues = assessments.map(({ id }) => `  ${variableName("assessment", id)}Value,`);
  const referenceValues = references.map(({ id }) => `  ${variableName("reference", id)}Value,`);
  return [
    "// Generated by tools/generate-content-registry.mjs. Do not edit by hand.",
    ...lessonImports,
    ...assessmentImports,
    ...referenceImports,
    "",
    "export const generatedLessonSources: readonly string[] = [",
    ...lessonValues,
    "];",
    "",
    "export const generatedAssessmentValues: readonly unknown[] = [",
    ...assessmentValues,
    "];",
    "",
    "export const generatedReferenceValues: readonly unknown[] = [",
    ...referenceValues,
    "];",
    "",
  ].join("\n");
}

function renderLearningLessonIds(lessons, stagedLessons) {
  const legacyMap = JSON.parse(readFileSync(legacyMapPath, "utf8"));
  if (!Array.isArray(legacyMap.lessons)) throw new Error("legacy content map has no lessons array");
  const migratedLegacyIds = new Set(
    lessons
      .filter(({ id }) => legacyMap.lessons.some((record) => record.id === id))
      .map(({ id }) => id),
  );
  const legacyStateIds = [...legacyMap.lessons]
    .sort((left, right) => left.id.localeCompare(right.id, undefined, { numeric: true }))
    .map((record) => {
      if (typeof record.slug !== "string" || record.slug.length === 0) {
        throw new Error(`legacy lesson ${String(record.id)} has no state slug`);
      }
      return record.slug;
    });
  const structuredIds = [...lessons]
    .filter(({ id }) => !migratedLegacyIds.has(id))
    .sort((left, right) => left.id.localeCompare(right.id, undefined, { numeric: true }))
    .map(({ id }) => id);
  const stagedIds = [...stagedLessons]
    .sort((left, right) => left.id.localeCompare(right.id, undefined, { numeric: true }))
    .map(({ id }) => id);
  const ids = [...legacyStateIds, ...structuredIds, ...stagedIds];
  if (new Set(ids).size !== ids.length) {
    throw new Error("learning-state IDs must be unique across legacy, canonical, and staged lessons");
  }
  const values = ids.map((id) => `  ${JSON.stringify(id)},`);
  return [
    "// Generated by tools/generate-content-registry.mjs. Do not edit by hand.",
    "export const generatedLearningLessonIds = [",
    ...values,
    "] as const;",
    "",
  ].join("\n");
}

function checkOrWrite(target, expected) {
  if (existsSync(target)) {
    const targetStatus = lstatSync(target);
    if (!targetStatus.isFile() || targetStatus.isSymbolicLink()) {
      throw new Error(`generated registry target is not a regular non-symlink file: ${repositoryPath(target)}`);
    }
  }
  if (checkOnly) {
    if (!existsSync(target) || !lstatSync(target).isFile()) {
      throw new Error(`generated registry is missing: ${repositoryPath(target)}`);
    }
    if (readFileSync(target, "utf8") !== expected) {
      throw new Error(
        `generated registry is stale: ${repositoryPath(target)}; run npm run generate:content-registry`,
      );
    }
    return;
  }
  writeFileSync(target, expected, "utf8");
}

const validation = validateRepositoryStructuredContent(repositoryRoot);
if (validation.issues.length > 0) {
  const first = validation.issues[0];
  throw new Error(
    `structured content must validate before registry generation: ${first.file}:${first.line} ${first.message}`,
  );
}

const lessons = collectFiles(lessonRoot, (name) => name === "lesson.md")
  .map(readLessonDescriptor)
  .sort((left, right) => left.volume.localeCompare(right.volume)
    || left.order - right.order || left.id.localeCompare(right.id));
const stagedLessons = collectFiles(stagedLessonRoot, (name) => name === "lesson.md")
  .map(readLessonDescriptor)
  .sort((left, right) => left.volume.localeCompare(right.volume)
    || left.order - right.order || left.id.localeCompare(right.id));
const assessments = collectFiles(assessmentRoot, (name) => /^ASM-\d{4}\.json$/.test(name))
  .map((file) => readJsonDescriptor(file, "ASM-"))
  .sort((left, right) => left.id.localeCompare(right.id, undefined, { numeric: true }));
const references = collectFiles(referenceRoot, (name) => /^REF-\d{4}\.json$/.test(name))
  .map((file) => readJsonDescriptor(file, "REF-"))
  .sort((left, right) => left.id.localeCompare(right.id, undefined, { numeric: true }));

checkOrWrite(lessonPathsTarget, renderLessonPaths(lessons));
checkOrWrite(recordRegistryTarget, renderRecordRegistry(lessons, assessments, references));
checkOrWrite(learningIdsTarget, renderLearningLessonIds(lessons, stagedLessons));
console.log(
  `${checkOnly ? "PASS" : "WROTE"} content registry lessons=${lessons.length} assessments=${assessments.length} references=${references.length}`,
);
